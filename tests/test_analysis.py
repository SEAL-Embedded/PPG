"""Unit tests for webapp/analysis.py.

The synthetic ECG + PPG generated by conftest produce realistic peak
counts (~30 R-peaks in 30 s @ 60 BPM), enough matched beats for
compute_ccc to return a real number, and a positively-skewed PPG so
SSQI / interpretation lines all fire.
"""

