# ── Loaders ─────────────────────────────────────────────────────────────────

class TestLoaders:

    def test_load_ecg_returns_three_arrays(self, synth_session):
        _, sdir, _ = synth_session
        ts_ms, sig, leads_off = analysis.load_ecg(
            os.path.join(sdir, "ecg_data.csv"))
        assert len(ts_ms) == len(sig) == len(leads_off)
        assert len(ts_ms) > 0
        # ts_us → ms conversion in the loader: the writer scales the
        # ts_us by 1_000_000, so ts_ms should be at least that big.
        assert ts_ms[0] >= 1e6
        # Leads-off column is always int.
        assert leads_off.dtype.kind in ("i", "u")

    def test_load_ppg_returns_two_arrays(self, synth_session):
        _, sdir, _ = synth_session
        ts_ms, sig = analysis.load_ppg(
            os.path.join(sdir, "ppg_data_ch0.csv"))
        assert len(ts_ms) == len(sig)
        assert len(ts_ms) > 0

    def test_load_ppg_skips_non_numeric_rows(self, tmp_path):
        """The loader uses on_bad_lines='skip' + to_numeric coercion;
        a stray header or partial flush mustn't poison the array."""
        path = tmp_path / "ppg.csv"
        with open(path, "w") as f:
            f.write("100,1.0\n200,2.0\nnot,a,number\n400,4.0\n")
        ts_ms, sig = analysis.load_ppg(str(path))
        # The "not,a,number" row has 3 cols — read_csv will skip or
        # to_numeric will drop it. Either way the valid rows survive.
        assert len(ts_ms) >= 3
        assert not np.isnan(ts_ms).any()


